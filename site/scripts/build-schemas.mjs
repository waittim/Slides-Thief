import { compile } from 'json-schema-to-typescript';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const ROOT_SCHEMAS_DIR = path.resolve(__dirname, '../../schemas');
const APP_SCHEMAS_DIR = path.resolve(__dirname, '../app/schemas');
const PUBLIC_SCHEMAS_DIR = path.resolve(__dirname, '../public/schemas');

function prepareSchemaForTs(schema) {
  const cloned = JSON.parse(JSON.stringify(schema));
  function walk(obj) {
    if (!obj || typeof obj !== 'object') return;
    if (Array.isArray(obj.prefixItems)) {
      obj.items = obj.prefixItems;
      delete obj.prefixItems;
    }
    for (const k of Object.keys(obj)) {
      walk(obj[k]);
    }
  }
  walk(cloned);
  return cloned;
}

async function main() {
  await fs.mkdir(APP_SCHEMAS_DIR, { recursive: true });
  await fs.mkdir(PUBLIC_SCHEMAS_DIR, { recursive: true });

  const schemaFiles = [
    {
      file: 'manual-quads.schema.json',
      outName: 'manual-quads.d.ts',
      titleName: 'ManualQuads',
    },
    {
      file: 'slide-lens-report.schema.json',
      outName: 'slide-lens-report.d.ts',
      titleName: 'SlideLensReport',
    },
  ];

  for (const { file, outName, titleName } of schemaFiles) {
    const schemaPath = path.join(ROOT_SCHEMAS_DIR, file);
    const tsOutPath = path.join(APP_SCHEMAS_DIR, outName);
    const publicOutPath = path.join(PUBLIC_SCHEMAS_DIR, file);

    console.log(`Compiling ${file} -> ${outName}...`);
    const rawContent = await fs.readFile(schemaPath, 'utf-8');
    const jsonSchema = JSON.parse(rawContent);

    const tsPrepared = prepareSchemaForTs(jsonSchema);
    const ts = await compile(tsPrepared, titleName, {
      unreachableDefinitions: true,
      style: {
        singleQuote: true,
      },
    });

    await fs.writeFile(tsOutPath, ts, 'utf-8');
    await fs.copyFile(schemaPath, publicOutPath);
    console.log(`Synced ${file} to public/schemas/`);
  }

  const indexContent = `/**
 * Auto-generated index re-exporting schema TypeScript definitions.
 * DO NOT EDIT MANUALLY. Generated by scripts/build-schemas.mjs
 */
export type { ManualQuads } from './manual-quads';
export type {
  SlideLensReport,
  BatchPrior,
  BatchSummary,
  Features,
  Quad as ReportQuad,
  Point as ReportPoint,
} from './slide-lens-report';
`;
  await fs.writeFile(path.join(APP_SCHEMAS_DIR, 'index.ts'), indexContent, 'utf-8');
  console.log('Schema build complete.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
